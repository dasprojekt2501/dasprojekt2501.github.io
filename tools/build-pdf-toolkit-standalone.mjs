function buildBootWarningMarkup(language) {
  const text = BOOT_WARNING_TEXT[language];
  return `<div id="standalone-unsupported" role="alert" hidden>
<strong>${text.heading}</strong>
<p>${text.body}</p>
<p><a href="${text.href}" rel="noopener noreferrer">${text.link}</a></p>
</div>
<style>
#standalone-unsupported { padding: 18px 20px; background: #3a1d1d; color: #ffd5d5; border-bottom: 2px solid #ff6b6b; font: 14px/1.7 -apple-system, BlinkMacSystemFont, 'Hiragino Sans', Meiryo, sans-serif; }
#standalone-unsupported p { margin: 6px 0 0; }
#standalone-unsupported a { color: #ffd5a0; }
</style>`;
}

const BOOT_DETECTOR = `<script>
(function () {
  function reveal() {
    var banner = document.getElementById('standalone-unsupported');
    if (banner) banner.hidden = false;
  }
  function revealWhenReady() {
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', reveal);
    else reveal();
  }
  var supportsImportMap = typeof HTMLScriptElement !== 'undefined'
    && typeof HTMLScriptElement.supports === 'function'
    && HTMLScriptElement.supports('importmap');
  if (!supportsImportMap) {
    revealWhenReady();
    return;
  }
  window.addEventListener('load', function () {
    setTimeout(function () { if (!window.__pdfToolkitBooted) reveal(); }, 2000);
  });
})();
</script>`;

function buildPrelude() {
  return `
// ---- standalone build prelude (generated by tools/build-pdf-toolkit-standalone.mjs) ----
const __standaloneAssets = JSON.parse(document.getElementById('standalone-assets').textContent);
function __standaloneBytes(base64) {
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}
class __StandaloneBinaryDataFactory {
  constructor(_options) {}
  async fetch({ kind, filename }) {
    const store = {
      cMapUrl: __standaloneAssets.cmaps,
      standardFontDataUrl: __standaloneAssets.fonts,
      wasmUrl: __standaloneAssets.wasm,
    }[kind];
    const data = store && store[filename];
    if (!data) throw new Error('Missing embedded asset: ' + kind + '/' + filename);
    return __standaloneBytes(data);
  }
}
// ----------------------------------------------------------------------------------------
`;
}

function patchAppJs(appJs) {
  let patched = replaceOnce(
    appJs,
    "import { PDFDocument, degrees } from './vendor/pdf-lib/pdf-lib.esm.min.js';\n",
    "import { PDFDocument, degrees } from './vendor/pdf-lib/pdf-lib.esm.min.js';\n" + buildPrelude(),
    'the pdf-lib import line',
  );
  patched = replaceOnce(
    patched,
    "GlobalWorkerOptions.workerSrc = new URL('pdf.worker.mjs', PDFJS_ROOT).href;",
    "GlobalWorkerOptions.workerSrc = 'data:text/javascript;base64,' + __standaloneAssets.worker;",
    'the worker source assignment',
  );
  patched = replaceOnce(
    patched,
    "    cMapUrl: new URL('cmaps/', PDFJS_ROOT).href,\n    cMapPacked: true,\n    standardFontDataUrl: new URL('standard_fonts/', PDFJS_ROOT).href,\n    wasmUrl: new URL('wasm/', PDFJS_ROOT).href,\n    useWasm: true,",
    "    cMapPacked: true,\n    useWorkerFetch: false,\n    BinaryDataFactory: __StandaloneBinaryDataFactory,\n    useWasm: true,",
    'the pdf.js asset URL options',
  );
  patched += '\nwindow.__pdfToolkitBooted = true;\n';
  if (patched.includes('</script')) {
    throw new Error('Standalone build: the application script contains "</script", which cannot be inlined safely.');
  }
  return patched;
}

export async function buildStandalonePages() {
  const [css, appJs, pdfjsBase64, pdfLibBase64, workerBase64] = await Promise.all([
    readText(resolve(appsDir, 'pdf-toolkit.css')),
    readText(resolve(appsDir, 'pdf-toolkit.js')),
    readBase64(resolve(pdfjsDir, 'pdf.mjs')),
    readBase64(resolve(appsDir, 'vendor/pdf-lib/pdf-lib.esm.min.js')),
    readBase64(resolve(pdfjsDir, 'pdf.worker.mjs')),
  ]);
  const assets = {
    worker: workerBase64,
    cmaps: await readAssetDirectory(resolve(pdfjsDir, 'cmaps')),
    fonts: await readAssetDirectory(resolve(pdfjsDir, 'standard_fonts')),
    wasm: await readAssetDirectory(resolve(pdfjsDir, 'wasm')),
  };
  const importMap = JSON.stringify({
    imports: {
      './vendor/pdfjs/pdf.mjs': 'data:text/javascript;base64,' + pdfjsBase64,
      './vendor/pdf-lib/pdf-lib.esm.min.js': 'data:text/javascript;base64,' + pdfLibBase64,
    },
  });
  const scriptsBlock = [
    '<script type="importmap">',
    importMap,
    '</script>',
    '<script id="standalone-assets" type="application/json">',
    JSON.stringify(assets),
    '</script>',
    BOOT_DETECTOR,
    '<script type="module">',
    patchAppJs(appJs),
    '</script>',
  ].join('\n');

  const pages = {};
  for (const [sourceName, outputName, language] of [
    ['pdf-toolkit.html', 'pdf-toolkit-standalone.html', 'ja'],
    ['pdf-toolkit-en.html', 'pdf-toolkit-standalone-en.html', 'en'],
  ]) {
    let html = await readText(resolve(appsDir, sourceName));
    html = replaceOnce(html, '<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + GENERATED_NOTICE + '\n', 'the doctype');
    html = replaceOnce(html, '<body>\n', '<body>\n' + buildBootWarningMarkup(language) + '\n', 'the body tag');
    html = replaceOnce(html, ONLINE_CSP, STANDALONE_CSP, 'the CSP meta tag');
    html = replaceOnce(html, '<title>PDF Toolkit</title>', '<title>PDF Toolkit (Standalone)</title>', 'the page title');
    html = replaceOnce(html, '<link rel="stylesheet" href="pdf-toolkit.css">', '<style>\n' + css + '</style>', 'the stylesheet link');
    html = replaceOnce(html, '<script type="module" src="pdf-toolkit.js"></script>', scriptsBlock, 'the module script tag');
    pages[outputName] = html;
  }
  return pages;
}

const isDirectRun = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirectRun) {
  const pages = await buildStandalonePages();
  for (const [name, content] of Object.entries(pages)) {
    await writeFile(resolve(appsDir, name), content);
    console.log(`Wrote apps/${name} (${(Buffer.byteLength(content) / 1048576).toFixed(1)} MB)`);
  }
}
